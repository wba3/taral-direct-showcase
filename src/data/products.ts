/**
 * Taral product catalog for the Taral Direct prototype.
 *
 * SPECIFICATIONS ARE REAL. Sizes, neck finishes, max fill capacities,
 * dimensions, case counts, case weights, pallet quantities, freight classes,
 * base item codes, stocking status and minimum order quantities are
 * transcribed from Taral's published product documents (product one-sheet,
 * product line & style illustrations, and the stocking program pages of the
 * August 2026 distributor list).
 *
 * PRICES ARE NOT REAL. Taral's distributor pricing is confidential and is
 * deliberately excluded. Every price in this prototype is generated by the
 * invented `illustrativePrice` helper below and is labeled as demo data
 * wherever it appears.
 */

export type Category =
  | "Regular Wall Jars"
  | "Thick Wall Jars"
  | "Double Wall Jars"
  | "Lids & Closures"
  | "Discs & Dust Covers"
  | "Add-ons";

/**
 * Stocking status from the published stocking program.
 * - "In stock": marked as a stock item, 1 case minimum (small order fee may apply).
 * - "Overrun — call": not a stock item, but overrun inventory may exist.
 * - "Made to order": non-stock; the item's MOQ or setup fee applies.
 */
export type StockStatus = "In stock" | "Overrun — call" | "Made to order";

export type StyleFamily =
  | "Regular (single) wall"
  | "Thick (heavy) wall"
  | "Double wall — round base"
  | "Double wall — straight base"
  | "Double wall — in-mold frost"
  | "Smooth side & top closure"
  | "Dome closure"
  | "Cosmetic dust cover"
  | "Jar insert"
  | "Program";

export interface Product {
  id: string;
  /** Base item code as published by Taral. */
  code: string;
  name: string;
  category: Category;
  styleFamily: StyleFamily;
  /** Nominal fill volume label, e.g. "1/4 oz". */
  size: string;
  /** Numeric ounces for range filtering. */
  sizeOz: number;
  /** Neck finish, e.g. "33mm-400". Null for non-threaded items. */
  neck: string | null;
  neckDiameterMm: number | null;
  material: string;
  /** Colors / resins Taral lists for this item, with stocking status. */
  materialOptions: { label: string; stocked: boolean }[];
  color: string;
  caseCount: number;
  caseWeightLb: number | null;
  casesPerPallet: number | null;
  freightClass: string | null;
  caseDims: string | null;
  stock: StockStatus;
  /** Non-stock minimum order quantity in pieces, when published. */
  moqEach: number | null;
  /** Mold setup / color purge note, when published. */
  setupNote: string | null;
  /** Lid styles Taral pairs with this jar (from the style comparison chart). */
  lidStyles?: string[];
  /** Invented distributor price for the demo account. Never a real price. */
  demoUnitPrice: number | null;
  quantityBreaks?: { minCases: number; unitPrice: number }[];
  dims?: { height?: string; opening?: string; maxFill?: string };
  availableToSell?: number;
  warehouses?: { code: string; name: string; qty: number }[];
  /** Which parts of the row come from Taral's published documents. */
  source: "published-specs" | "illustrative";
  notes?: string;
}

