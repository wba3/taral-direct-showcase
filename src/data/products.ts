/**
 * Invented pricing. Deliberately synthetic so no confidential figure appears:
 * a flat base plus a coefficient on fill volume, with two demo quantity breaks.
 */
function illustrativePrice(base: number) {
  const round = (n: number) => Math.round(n * 1000) / 1000;
  const unit = round(base);
  return {
    demoUnitPrice: unit,
    quantityBreaks: [
      { minCases: 1, unitPrice: unit },
      { minCases: 5, unitPrice: round(unit * 0.94) },
      { minCases: 20, unitPrice: round(unit * 0.89) },
    ],
  };
}

const jarPrice = (ml: number) => illustrativePrice(0.045 + ml * 0.0034);
const capPrice = (mm: number, lined: boolean) =>
  illustrativePrice(mm * 0.0021 + (lined ? 0.03 : 0));
const discPrice = (mm: number) => illustrativePrice(0.006 + mm * 0.00035);

const OPT = (label: string, stocked: boolean) => ({ label, stocked });

/** Stock status follows the published program: any stocked color ⇒ stock item. */
function statusFor(options: { label: string; stocked: boolean }[]): StockStatus {
  if (options.some((o) => o.stocked)) return "In stock";
  return options.length > 0 ? "Overrun — call" : "Made to order";
}

