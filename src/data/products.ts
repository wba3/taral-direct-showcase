  PRODUCTS.filter((p) => {
    if (p.id === product.id || p.neck === null || p.neck !== product.neck) return false;
    if (isJar(product)) {
      if (p.category === "Lids & Closures") {
        const allowed = product.lidStyles ?? [];
        return p.styleFamily === "Dome closure"
          ? allowed.includes("Dome cap")
          : allowed.includes("Smooth side & top");
      }
      return p.category === "Discs & Dust Covers" || p.category === "Add-ons";
    }
    return isJar(p);
  });

export const money = (n: number, digits = 2) =>
  `$${n.toLocaleString("en-US", { minimumFractionDigits: digits, maximumFractionDigits: digits })}`;
