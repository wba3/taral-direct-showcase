function jarProduct(
  seed: JarSeed,
  category: Category,
  family: StyleFamily,
  name: string,
  lidStyles: string[],
  diameterLabel: "Opening (inside)" | "Outside diameter",
): Product {
  const options = seed.options;
  const stocked = options.filter((o) => o.stocked);
  const status = statusFor(options);
  const price = jarPrice(seed.maxFillMl);
  return {
    id: seed.id,
    code: seed.code,
    name,
    category,
    styleFamily: family,
    size: seed.size,
    sizeOz: seed.sizeOz,
    neck: `${seed.neckMm}mm-400`,
    neckDiameterMm: seed.neckMm,
    material: options[0]?.label ?? "Polypropylene (PP)",
    materialOptions: options,
    color: stocked[0]?.label ?? options[0]?.label ?? "Quoted per run",
    caseCount: seed.caseCount,
    caseWeightLb: seed.caseWeightLb,
    casesPerPallet: seed.casesPerPallet,
    freightClass: seed.freightClass,
    caseDims: seed.caseDims,
    stock: status,
    moqEach: seed.moqEach,
    setupNote: seed.setupNote ?? null,
    lidStyles,
    ...(status === "In stock" ? price : { demoUnitPrice: null }),
    dims: {
      height: seed.height,
      opening: `${seed.diameter} ${diameterLabel === "Outside diameter" ? "OD" : "ID"}`,
      maxFill: `${seed.maxFillMl} ml`,
    },
    availableToSell:
      status === "In stock" ? seed.caseCount * (seed.casesPerPallet >= 40 ? 34 : 18) : 0,
    warehouses:
      status === "In stock"
        ? [
            {
              code: "CRN",
              name: "Corona, CA",
              qty: seed.caseCount * (seed.casesPerPallet >= 40 ? 34 : 18),
            },
          ]
        : [],
    source: "published-specs",
    ...(seed.notes ? { notes: seed.notes } : {}),
  };
}

